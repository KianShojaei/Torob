def brands_flat() -> list[str]:
    out: list[str] = []
    for c in CATEGORIES:
        out.extend(c.brands)
    return sorted(set(out))


def key_specs_for(category_name: str | None) -> tuple[str, ...]:
    if not category_name:
        return ()
    c = CATEGORY_BY_NAME.get(category_name)
    return c.key_specs if c else ()
